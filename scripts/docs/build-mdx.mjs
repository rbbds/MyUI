// Generates src/docs/data/*.json and src/docs/components/*.mdx from docs/content.
import { writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { docs } from '../../docs/content/index.mjs';

rmSync('src/docs/data', { recursive: true, force: true });
rmSync('src/docs/components', { recursive: true, force: true });
mkdirSync('src/docs/data', { recursive: true });
mkdirSync('src/docs/components', { recursive: true });

for (const d of docs) {
  const { id, stories, ...data } = d;
  writeFileSync(`src/docs/data/${id}.json`, JSON.stringify(data, null, 2) + '\n');
  const examples = stories.items.map((s) => `<Canvas of={Stories.${s}} />`).join('\n\n');
  const mdx = `{/* Generated by scripts/docs/build-mdx.mjs. Edit docs/content/*.mjs instead. */}
import { Meta, Canvas } from '@storybook/addon-docs/blocks';
import * as Stories from '../../components/${stories.file}';
import { ComponentDoc, DocHeader } from '../ComponentDoc';
import doc from '../data/${id}.json';

<Meta of={Stories} name="Docs" />

<DocHeader doc={doc} />

## Voorbeelden

${examples}

<ComponentDoc doc={doc} />
`;
  writeFileSync(`src/docs/components/${id}.mdx`, mdx);
}
console.log(`${docs.length} docs written`);
